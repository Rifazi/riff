import { DOMAIN_DOC, MAP_PATH, WAYFINDING_GUIDE_PATH, WAYFINDING_REPO_URL, type WayfindingConfig } from './architecture.js';

// Marks docs/wayfinding.md as Riff's, so it's refreshed on setup without
// ever overwriting a hand-written file at that path.
export const GUIDE_MARKER = '<!-- generated by riff-dev-sessions: wayfinding guide -->';

export type ArchitectureBriefingRole = 'requirements' | 'plan' | 'coding' | 'qa';

/** MAP.md for a repo adopting Wayfinding: the reference template, with nothing listed yet. */
export function renderMapTemplate(today: string): string {
  return `# Map

<!--
One line per top-level domain and junction. Child domains are listed in
their parent's ${DOMAIN_DOC}, not here. Keep this file short enough to read in
full on every task. See ${WAYFINDING_GUIDE_PATH}.
-->

| Domain | Owns | Interface |
| --- | --- | --- |

## Structural changes

<!-- Every created, merged, split, or promoted domain, newest first. -->
- ${today}  adopted Wayfinding Architecture: domains are added as changes need them

## Legacy tables

<!-- Tables with more than one writer, until they are migrated. -->
- none

## External sequences

<!--
Workflows that cross domains and leave the code you control: other systems,
other teams' services, other repositories.
-->
`;
}

export function renderDomainTemplate(config: WayfindingConfig): string {
  return `# <domain>

Parent: <parent domain, or "none (top-level domain)">
Owns: <the decisions this domain makes>
Owns data: <tables this domain writes, or "none">
Child domains: <names, or "none">
Does not own: <nearby decisions that live elsewhere (see <domain>)>
Interface: <public functions in ${config.interfaceFile}>
Checkpoint: <command that runs this domain's tests>

## Rules
- <rule, in plain English>
  Why: <reason, source, or date>
  Enforced by: <test file> › "<test name>"

## Hidden behavior
- <what the code cannot tell you: scheduled jobs, external consumers, imports that overwrite data, traps>

## Recipes
### <common task>
1. <step>
2. Add a test named after the rule
3. Add the rule to "Rules" with its test
4. Run the checkpoint

## Mirrors
- none

## Consumers
<!-- generated: do not edit -->
- none
<!-- end generated -->`;
}

/** docs/wayfinding.md: the procedure, for the humans and agents working in the repo (indexed by search_docs). */
export function renderWayfindingGuide(config: WayfindingConfig): string {
  const src = config.srcDir === '.' ? 'the repo root' : `\`${config.srcDir}/\``;
  return `${GUIDE_MARKER}
# How to change this codebase: Wayfinding Architecture

This repository follows [Wayfinding Architecture](${WAYFINDING_REPO_URL}).
**Every important decision is owned by exactly one domain. Find it before you change it.**

Every change answers three questions:

1. **Where does this change belong?** The domain that owns the decision.
2. **What can it affect?** That domain's consumers, discovered and declared.
3. **How much should change at once?** One segment: a step that can be validated and reverted on its own.

## Layout

| Concept | Here |
| --- | --- |
| Domain | A folder under ${src} with a \`${DOMAIN_DOC}\`. Owns a set of decisions and the data they need; only it writes its own data. |
| Public interface | The domain's \`${config.interfaceFile}\`: the only file other domains import. |
| Child domain | A domain folder inside a domain. Visible only to its parent (and its siblings). Never depends on its parent. |
| Junction | A domain whose rules combine other domains' decisions (\`Kind: junction\` and \`Inputs:\` in its ${DOMAIN_DOC}). |
| Map | \`${MAP_PATH}\` at the repo root: one line per top-level domain and junction. |
| Segment | A bounded step of a change: one decision through one domain's boundary, validated and revertible on its own. |

## Before writing code

1. Read \`${MAP_PATH}\` and find the domain that owns the decision you are changing.
2. Read that domain's \`${DOMAIN_DOC}\`: Rules, Hidden behavior, Recipes. If the decision lives in a child domain, read the parent's first.
3. Write down the route:

   \`\`\`
   Requirement:  <the request, in one or two lines>
   Domains:      <domain>   <what changes there>
   Consumers:    <discovered and declared consumers of any interface you change>
   Segments:     1. <domain>  <change>
                 2. ...
   \`\`\`

   If the request mixes several decisions, split it first: one line per decision, with the domain that owns it.

## While changing code

- Change a decision only in its owning domain.
- Reach other domains only through their \`${config.interfaceFile}\`. Never import another domain's other files.
- From outside a parent domain, never import its child domains.
- Never re-implement another domain's decision; call it.
- Write a table only from the domain that owns it.
- If no domain owns the decision and only one place uses it, record it under that domain's "Owns". Create a new domain only
  when a second place needs it; do it in its own segment and log it in \`${MAP_PATH}\` under Structural changes.
- If \`${DOMAIN_DOC}\` and the code disagree, a test this segment did not modify decides. Fix whichever side is wrong and note the correction.
- Work one segment at a time. Each segment ends with its checkpoint passing.
- Prefer expand/contract: add the new shape alongside the old, move consumers, then remove the old shape in a later segment.
  Schema changes are forward-only and follow the same pattern at the column level.

## Before finishing

- Update Rules, Hidden behavior and Recipes in every \`${DOMAIN_DOC}\` you touched, in the same segment as the code. Anchor
  every rule to a test (\`Enforced by: <test file> › "<test name>"\`).
- Never edit generated sections by hand; regenerate them.
- Put any change to "Owns", "Does not own" or Mirrors in its own segment, so QA sees it separately.
- Run the checkpoint and the mechanical checks.
- Hand the route, the diff and the docs to an independent QA review.

## What goes in the docs

Write down what the code cannot tell you. Do not restate what it can, unless the restatement is anchored to a test.

- **Freely:** workflows that leave the repository, why a rule exists, traps ("never call X before Y"), business vocabulary, recipes.
- **Anchored:** business rules in plain English, each with an *Enforced by* test. A rule without one is a second authority in prose.

| Section | Updated by | Validated by |
| --- | --- | --- |
| Generated (Consumers) | A script, never by hand | The mechanical checks |
| Rules, Hidden behavior, Recipes | The change, in the same segment as the code | QA |
| Ownership (Owns, Does not own, Mirrors, junction inputs) | The change, in a separate segment | QA, as a boundary change |

## Mechanical checks

In Riff Dev Sessions the agents run \`audit_architecture\`, which checks: other domains reached only through
\`${config.interfaceFile}\`; child domains visible only inside their parent; no child depending on its parent; no dependency
cycles; every rule anchored to a test that exists; no rule in two domains; files named in Recipes exist; the generated Consumers
sections match the code; every top-level domain on \`${MAP_PATH}\` (junctions marked as such); and, where the code defines TypeORM
entities, one writer per table with the domain's prefix, listed under "Owns data". The reference repo's
\`example/tools/check.ts\` is a standalone version of the same checks to wire into CI.

## ${DOMAIN_DOC} template

\`\`\`markdown
${renderDomainTemplate(config)}
\`\`\`

## Adopting it in an existing codebase

Wayfinding doesn't need a rewrite. Legacy code starts off the map, and the map grows with each change: find the decision the
next change touches, draw a domain around it (an adapter in front of legacy code if needed), list its consumers, add it to
\`${MAP_PATH}\`, and plan the change as segments. Tables with several writers are declared under "Legacy tables" in
\`${MAP_PATH}\`; existing writers are declared exceptions, and the list only shrinks.
`;
}

const SHARED = (c: WayfindingConfig) =>
  `This app follows Wayfinding Architecture: every important decision is owned by exactly one domain. Domains are folders ` +
  `under ${c.srcDir === '.' ? 'the repo root' : `${c.srcDir}/`} with a ${DOMAIN_DOC} (Owns, Does not own, Interface, Checkpoint, Rules ` +
  `anchored to tests, Hidden behavior, Recipes, Mirrors, a generated Consumers list). ${MAP_PATH} at the repo root indexes the ` +
  `top-level domains and junctions. Other domains are reached only through a domain's ${c.interfaceFile}; a child domain is ` +
  `visible only inside its parent. read_doc reads ${MAP_PATH} and any ${DOMAIN_DOC} (by path, optionally one heading). The full ` +
  `procedure, with the ${DOMAIN_DOC} template, is ${WAYFINDING_GUIDE_PATH}. audit_architecture runs the mechanical checks and ` +
  `lists the domains.`;

/**
 * The per-role architecture section of an agent's system prompt. Appended
 * after any prompt override, which replaces the base prompt wholesale.
 */
export function wayfindingBriefing(role: ArchitectureBriefingRole, config: WayfindingConfig): string {
  const byRole: Record<ArchitectureBriefingRole, string> = {
    requirements:
      `Read ${MAP_PATH} with read_doc before writing requirements, and a domain's ${DOMAIN_DOC} the same way (e.g. read_doc ` +
      `with heading "Hidden behavior"). For each requirement, name the decision it changes and the ` +
      `domain that owns it, or "no domain yet". When a request mixes several decisions, list them one per line with their ` +
      `owning domain in a "Decisions and owning domains" section of the requirements document. Read the Hidden behavior of ` +
      `those domains' ${DOMAIN_DOC}: anything that constrains the request (an external consumer, data overwritten by an ` +
      `import, a rule that must keep holding) goes in as a constraint or an open question. Leave segments to the plan.`,
    plan:
      `Before writing the plan, read ${MAP_PATH} and the ${DOMAIN_DOC} of every domain involved (a parent before its child), ` +
      `and run audit_architecture. Open the plan with a "Route" section:\n\n` +
      '```\nRequirement:  <the request>\nDomains:      <domain>   <what changes there>\n' +
      'Consumers:    <discovered (Consumers sections, audit) and declared (Hidden behavior, external) consumers of any interface that changes>\n' +
      'Segments:     1. <domain>  <change>\n```\n\n' +
      `Make each plan step one segment: one decision through one domain's boundary, describable in advance, validated and ` +
      `revertible on its own. Name the domain and its Checkpoint command in the step, and the ${DOMAIN_DOC} sections the step ` +
      `updates. Changes to Owns, Does not own, Mirrors or junction inputs get their own step, as do creating, merging or splitting ` +
      `a domain (logged under Structural changes in ${MAP_PATH}). When an interface with separately deployed, external or ` +
      `persisted consumers changes, plan expand then contract: add the new shape, move consumers one step at a time, remove the ` +
      `old shape last; schema changes are forward-only. Behavior-neutral work (refactors, upgrades) takes the short route: ` +
      `domain, interface unchanged, consumers, segments. A decision gets a new domain only when a second place needs it.`,
    coding:
      `Read first, update last. Before changing code, read ${MAP_PATH} and the ${DOMAIN_DOC} of the domain the step names ` +
      `(its parent's first), and follow the plan's Route. Change a decision only in its owning domain; reach other domains only ` +
      `through their ${config.interfaceFile}; never import a child domain from outside its parent; never re-implement another ` +
      `domain's decision, call it; write a table only from its owning domain. In the same step as the code, update that ` +
      `${DOMAIN_DOC}'s Rules (each anchored: Enforced by: <test file> › "<test name>", with that test written), Hidden behavior ` +
      `and Recipes. Ownership changes (Owns, Does not own, Mirrors) and new domains go in their own step and commit; log a new, ` +
      `merged or split domain in ${MAP_PATH}. Never hand-edit the generated Consumers block: audit_architecture({ regenerate: ` +
      `true }) rewrites it. If ${DOMAIN_DOC} and the code disagree, a test this step didn't modify decides; fix the wrong side ` +
      `and say so. Finish each step with the domain's Checkpoint passing and audit_architecture showing no problems in the ` +
      `domains you touched. Use note_for_qa for the route you actually took if it differs from the plan, any ownership change, ` +
      `and hidden behavior you discovered. When splitting work across a team, give each workstream whole domains as its owned paths.`,
    qa:
      `You are the independent QA the procedure calls for: validate the code and the docs together. Run audit_architecture: ` +
      `it reports the structural and doc checks, which domains the branch touched and any ownership or structural edits. Flag ` +
      `as findings: an audit problem in MAP.md or a domain the branch touched; a changed business rule without a matching ` +
      `change in that domain's Rules, anchored to a test that exists; Owns, Does not own or Mirrors changed without being its ` +
      `own commit/step, or inconsistent with the guardrails; a new domain not logged in ${MAP_PATH}; duplicate authority (logic ` +
      `outside the owning domain that re-implements its decision), undeclared mirrors, and misplaced decisions (a rule ` +
      `implemented in a consumer); hidden behavior the work relied on or discovered but didn't record; and a diff touching ` +
      `domains the plan's Route didn't name. When the docs and the code disagree and no test the branch didn't modify settles ` +
      `which is right, say it needs the human's decision rather than guessing. Problems only in domains the branch didn't touch ` +
      `are not its findings.`,
  };
  return `\n\n# Architecture: Wayfinding\n\n${SHARED(config)}\n\n${byRole[role]}`;
}
